import {matterImport,matterImportState} from './imports/matters';
import {numberSettings,saveNumberSettings} from './numbering';
import {Hono,type Context} from 'hono';
import {deploymentHealth} from '../base/deployment-health';
import {type Bindings,runtimeBindings} from '../auth.server';
import {person,agent} from './session';
import {Fault,insist,type Actor,type Data} from './model';
import {conflictSearch,openMatter,workspace,matterDetail,grantMatter} from './matters';
import {saveMember,inviteMember,createAgentKey,revokeAgentKey,teamState} from './team';
import {addEntry,listBilling,prepareBill,approveBill,exportBill,voidBill,correctBill} from './billing';
import {listDocuments,saveDocument,documentFile} from './documents';
import {listDeadlines,proposeDeadline,confirmDeadline,completeDeadline} from './deadlines';
import {propose,decideProposal} from './proposals';
import {importAction,importState} from './imports';
import {backup,restore,eraseDocument} from './archive';
import {firmSettings,saveFirm,importFirm,exportFirm} from './firm';
import {placeHold,releaseHold,setSchedule,retentionState,disposeDocument} from './retention';
type C=Context<{Bindings:Bindings}>;
export const api=new Hono<{Bindings:Bindings}>();
api.get('/health',c=>c.json({status:'ok',...deploymentHealth(c.env)}));
api.use('/api/*',async(c,next)=>{await next();c.header('cache-control','no-store');c.header('x-content-type-options','nosniff');c.header('referrer-policy','no-referrer');});
api.onError((e,c)=>{if(e instanceof Fault)return c.json({error:e.message},e.status as 400);if(e instanceof SyntaxError)return c.json({error:'Supply valid JSON'},400);if('code' in e && /^(erasure_epoch|erased_row)/.test(String(e.code)))return c.json({error:'This archive predates an erasure. Restore the latest archive ('+String(e.code)+').'},409);if('code' in e)return c.json({error:String(e.code)},('status'in e?Number(e.status):409) as 400);console.error(e);return c.json({error:'The operation failed. Refresh before trying again.'},500);});
async function body(c:C):Promise<Data>{const raw=await c.req.text();insist(raw.length<=24_000_000,'Request too large',413);const b=JSON.parse(raw);insist(b&&typeof b==='object'&&!Array.isArray(b),'Supply a JSON object');return b;}
const db=(c:C)=>runtimeBindings(c.env).DB;
const param=(c:C,key='id')=>c.req.param(key)!;
const as=(fn:(a:Actor,c:C)=>Promise<unknown>)=>async(c:C)=>{const result=await fn(await person(c.req.raw,c.env),c);return result instanceof Response?result:c.json(result);};
const asAgent=(fn:(a:Actor,c:C)=>Promise<unknown>)=>async(c:C)=>c.json(await fn(await agent(c.req.raw,c.env),c));
api.get('/api/satchel/numbering',as((a,c)=>numberSettings(db(c))));
api.post('/api/satchel/numbering',as(async(a,c)=>saveNumberSettings(db(c),a,await body(c))));
api.get('/api/satchel/state',as((a,c)=>workspace(db(c),a)));
api.post('/api/satchel/conflicts',as(async(a,c)=>conflictSearch(db(c),a,await body(c))));
api.post('/api/satchel/matters',as(async(a,c)=>openMatter(db(c),a,await body(c))));
api.get('/api/satchel/matters/:id',as((a,c)=>matterDetail(db(c),a,param(c))));
api.post('/api/satchel/matters/:id/access',as(async(a,c)=>grantMatter(db(c),a,param(c),await body(c))));
api.get('/api/satchel/matters/:id/billing',as((a,c)=>listBilling(db(c),a,param(c))));
api.post('/api/satchel/matters/:id/entries',as(async(a,c)=>addEntry(db(c),a,param(c),await body(c))));
api.post('/api/satchel/matters/:id/bills',as(async(a,c)=>prepareBill(db(c),a,param(c),await body(c))));
api.post('/api/satchel/bills/:id/approve',as(async(a,c)=>approveBill(db(c),a,param(c),await body(c))));
api.post('/api/satchel/bills/:id/void',as(async(a,c)=>voidBill(db(c),a,param(c),await body(c))));
api.post('/api/satchel/bills/:id/correct',as(async(a,c)=>correctBill(db(c),a,param(c),await body(c))));
api.get('/api/satchel/bills/:id/export',as((a,c)=>exportBill(db(c),a,param(c))));
api.get('/api/satchel/matters/:id/documents',as((a,c)=>listDocuments(db(c),a,param(c))));
api.post('/api/satchel/matters/:id/documents',as(async(a,c)=>saveDocument(db(c),a,param(c),await body(c))));
api.get('/api/satchel/documents/:id/file',as((a,c)=>documentFile(db(c),a,param(c),c.req.query('version')?Number(c.req.query('version')):undefined)));
api.post('/api/satchel/documents/:id/erase',as(async(a,c)=>eraseDocument(db(c),a,param(c),await body(c))));
api.get('/api/satchel/matters/:id/deadlines',as((a,c)=>listDeadlines(db(c),a,param(c))));
api.post('/api/satchel/matters/:id/deadlines',as(async(a,c)=>proposeDeadline(db(c),a,param(c),await body(c))));
api.post('/api/satchel/deadlines/:id/confirm',as(async(a,c)=>confirmDeadline(db(c),a,param(c),await body(c))));
api.post('/api/satchel/deadlines/:id/complete',as(async(a,c)=>completeDeadline(db(c),a,param(c),await body(c))));
api.get('/api/satchel/retention',as((a,c)=>retentionState(db(c),a,c.req.query('matter')||undefined)));
api.post('/api/satchel/holds',as(async(a,c)=>placeHold(db(c),a,await body(c))));
api.post('/api/satchel/holds/:id/release',as(async(a,c)=>releaseHold(db(c),a,param(c),await body(c))));
api.post('/api/satchel/retention',as(async(a,c)=>setSchedule(db(c),a,await body(c))));
api.post('/api/satchel/documents/:id/dispose',as(async(a,c)=>disposeDocument(db(c),a,param(c),await body(c))));
api.get('/api/satchel/firm',as((a,c)=>firmSettings(db(c))));
api.post('/api/satchel/firm',as(async(a,c)=>saveFirm(db(c),a,await body(c))));
api.get('/api/satchel/firm/export',as((a,c)=>exportFirm(db(c),a)));
api.post('/api/satchel/firm/import',as(async(a,c)=>importFirm(db(c),a,await body(c))));
api.get('/api/satchel/team',as((a,c)=>teamState(db(c),a)));
api.post('/api/satchel/team',as(async(a,c)=>saveMember(db(c),a,await body(c))));
api.post('/api/satchel/team/invite',as(async(a,c)=>inviteMember(c.req.raw,c.env,a,await body(c))));
api.post('/api/satchel/keys',as(async(a,c)=>createAgentKey(db(c),a,await body(c))));
api.post('/api/satchel/keys/:id/revoke',as((a,c)=>revokeAgentKey(db(c),a,param(c))));
api.post('/api/satchel/proposals/:id/decide',as(async(a,c)=>decideProposal(db(c),a,param(c),await body(c))));
api.get('/api/satchel/agent/matters/:id',asAgent(async(a,c)=>({billing:await listBilling(db(c),a,param(c)),documents:await listDocuments(db(c),a,param(c)),deadlines:await listDeadlines(db(c),a,param(c))})));
api.get('/api/satchel/agent/context',asAgent((a,c)=>workspace(db(c),a)));
api.post('/api/satchel/agent/:command',asAgent(async(a,c)=>propose(db(c),a,param(c,'command').replace(/^prepare-/,''),await body(c))));
api.get('/api/satchel/matter-import',as((a,c)=>matterImportState(db(c),a)));
api.post('/api/satchel/matter-import/:op',as(async(a,c)=>matterImport(db(c),a,param(c,'op'),await body(c))));
api.get('/api/satchel/import',as((a,c)=>importState(db(c),a)));
api.post('/api/satchel/import/:op',as(async(a,c)=>importAction(db(c),a,param(c,'op'),await body(c))));
api.get('/api/satchel/backup',as((a,c)=>backup(db(c),a)));
api.post('/api/satchel/restore',as(async(a,c)=>restore(db(c),a,await body(c))));
